"""
Filter JSONL prompt datasets for explicit textual clues that the writer may be
18–25 years old, processing every .jsonl file in an input folder recursively.

The output folder is named <input-folder-name>_tya by default. The relative
directory structure is preserved, and each output filename gets a _tya suffix.

Examples:
  python filter_18_25.py --input-folder processed_data
  python filter_18_25.py --input-folder processed_data --output-folder processed_data_tya
  python filter_18_25.py --input-folder data --include-life-stage

This uses keyword/regex pattern matching only. It does NOT determine a person's
actual age. Slang, informal language, and vague style clues are intentionally
excluded. 
"""

import argparse
import json
import re
from pathlib import Path
from typing import Any, Iterable

# Expanded age regex to catch:
# 1. Standard digits (18-25), short forms (18yo, 18 y/o, 18 yr old)
# 2. Spelled out numbers (eighteen to twenty-five)
# 3. Dynamic birth year matching for 18-25 range (2001 - 2008)
AGE_PATTERNS = [
    # Digits with optional y/o, yo, year old, yrs old
    re.compile(
        r"\b(?:i am|i'm|im|i’m|i am currently|i’m currently|as an?)\s+(?:about\s+)?"
        r"(?:1[8-9]|2[0-5])\s*(?:[- ]?(?:year[s]?|yr[s]?)[\s-]?old|y/?o)\b",
        re.IGNORECASE,
    ),
    # Turning / Just turned
    re.compile(
        r"\b(?:i am|i'm|im|i’m|i just turned|i recently turned|i'm turning|i’m turning)\s+"
        r"(?:1[8-9]|2[0-5])\b",
        re.IGNORECASE,
    ),
    # Aged X
    re.compile(
        r"\b(?:i am|i'm|im|i’m)\s+(?:aged\s+)?(?:1[8-9]|2[0-5])\b",
        re.IGNORECASE,
    ),
    # Explicit declaration: Age: 21, my age is 22
    re.compile(
        r"\b(?:my age is|age:\s*)(?:1[8-9]|2[0-5])\b",
        re.IGNORECASE,
    ),
    # Textual numbers (eighteen - twenty-five)
    re.compile(
        r"\b(?:i am|i'm|im|i’m)\s+(?:eighteen|nineteen|twenty|twenty[- ]one|twenty[- ]two|"
        r"twenty[- ]three|twenty[- ]four|twenty[- ]five)\s*(?:[- ]?years?[- ]old)?\b",
        re.IGNORECASE,
    ),
    # Decades / Life stages
    re.compile(
        r"\b(?:i am|i'm|im|i’m)\s+in\s+my\s+(?:early|mid|late)\s+twenties\b",
        re.IGNORECASE,
    ),
    # Birth year detection (2001–2008 covering 18-25 range)
    re.compile(
        r"\b(?:i was born in|born in)\s+(?:200[1-8])\b",
        re.IGNORECASE,
    ),
]

LIFE_STAGE_PATTERNS = [
    re.compile(r"\b(?:i am|i'm|im|i’m)\s+(?:a\s+)?(?:college|university)\s+(?:student|undergrad|freshman|sophomore|junior|senior)\b", re.IGNORECASE),
    re.compile(r"\bmy\s+(?:freshman|sophomore|junior|senior)\s+year\s+of\s+(?:college|uni|university)\b", re.IGNORECASE),
]

def collect_texts(row: dict[str, Any], text_key: str | None = None) -> list[str]:
    """Extract candidate prompt text from all schema variants generated by prepare_dataset.py."""
    values: list[str] = []

    if text_key and text_key in row:
        val = row[text_key]
        if isinstance(val, str) and val.strip():
            return [val.strip()]
        if isinstance(val, list):
            return [t.strip() for t in val if isinstance(t, str) and t.strip()]

    # Handle ShareChat ("plain_text")
    if "plain_text" in row and isinstance(row["plain_text"], str):
        values.append(row["plain_text"])

    # Handle WildChat ("prompts": ["...", "..."])
    if "prompts" in row and isinstance(row["prompts"], list):
        for p in row["prompts"]:
            if isinstance(p, str) and p.strip():
                values.append(p.strip())

    # Handle LMSYS ("conversation": [{"role": "user", "content": "..."}, ...])
    if "conversation" in row and isinstance(row["conversation"], list):
        for turn in row["conversation"]:
            if isinstance(turn, dict):
                content = turn.get("content")
                if isinstance(content, str) and content.strip():
                    values.append(content.strip())

    return list(dict.fromkeys(values))


def find_clues(texts: Iterable[str], include_life_stage: bool = False) -> list[dict[str, str]]:
    matches: list[dict[str, str]] = []
    patterns = [("explicit_age", p) for p in AGE_PATTERNS]
    if include_life_stage:
        patterns += [("life_stage_only", p) for p in LIFE_STAGE_PATTERNS]

    for text in texts:

        for clue_type, pattern in patterns:
            for match in pattern.finditer(text):
                matches.append({
                    "clue_type": clue_type,
                    "matched_text": match.group(0),
                    "source_text": text,
                })
    return matches


def process_file(input_path: Path, output_path: Path, include_life_stage: bool,
                 text_key: str | None) -> tuple[int, int]:
    total = 0
    kept = 0
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with input_path.open("r", encoding="utf-8") as src, output_path.open(
        "w", encoding="utf-8"
    ) as dst:
        for line in src:
            if not line.strip():
                continue
            total += 1

            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue

            if not isinstance(row, dict):
                continue

            texts = collect_texts(row, text_key)
            clues = find_clues(texts, include_life_stage)

            if clues:
                row["_age_pattern_matches"] = clues
                row["_age_range_candidate"] = "18-25"
                dst.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")
                kept += 1

    return total, kept


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Filter JSONL files for explicit self-reported age clues 18–25."
    )
    parser.add_argument("--input-folder", required=True)
    parser.add_argument("--output-folder")
    parser.add_argument("--text-key")
    parser.add_argument("--include-life-stage", action="store_true")
    args = parser.parse_args()

    input_root = Path(args.input_folder).expanduser().resolve()
    if not input_root.exists() or not input_root.is_dir():
        raise SystemExit(f"Input folder invalid: {input_root}")

    output_root = Path(args.output_folder).expanduser().resolve() if args.output_folder else input_root.parent / f"{input_root.name}_tya"

    files = sorted(p for p in input_root.rglob("*.jsonl") if p.is_file())
    total_rows, kept_rows = 0, 0

    for input_file in files:
        relative = input_file.relative_to(input_root)
        output_file = output_root / relative.parent / f"{input_file.stem}_tya{input_file.suffix}"

        total, kept = process_file(
            input_file, output_file, args.include_life_stage, args.text_key
        )
        total_rows += total
        kept_rows += kept
        print(f"{relative}: scanned {total:,}, kept {kept:,}")

    print(f"\nFinished. Scanned: {total_rows:,}, Kept: {kept_rows:,}")


if __name__ == "__main__":
    main()
